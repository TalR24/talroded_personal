#!/usr/bin/env python3
"""
sync_impact.py: feed the PUBLIC entries of the private impact ledger into
profile_facts.json under the new top-level key "impact", and export the whole
ledger (public and private) as Markdown for grant reports and applications.

The ledger lives in the private premium repo
(nycur-data-premium/planning/impact_ledger.yaml; schema in its header comment).
This script never rewrites "press", "talks" or "bylines"; it only REPORTS where
those keys and the public ledger entries disagree, so Tal or a session can
reconcile them deliberately. Every other key in profile_facts.json is preserved,
and the file is written the way copy_check.py writes it (indent=2,
ensure_ascii=False, trailing newline).

Usage:
    python3 scripts/sync_impact.py --ledger <path>                 # validate, report, write "impact"
    python3 scripts/sync_impact.py --ledger <path> --check         # validate, report, show diff, write nothing
    python3 scripts/sync_impact.py --ledger <path> --export <md>   # also write the Markdown export
"""
from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from datetime import date, datetime
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
FACTS = ROOT / "profile_facts.json"

TYPES = ["press_citation", "byline", "talk", "tool_use", "dataset_use",
         "policy_use", "grant_award", "endorsement", "other"]
PROJECTS = ["nycuriosity", "trackers", "block_party", "sce", "cb_tools", "studio", "data_science"]
FIELDS = ["id", "date", "type", "title", "outlet", "url", "project", "summary", "public", "source", "added"]
REQUIRED = ["id", "date", "type", "title", "outlet", "project", "summary", "public", "source", "added"]
TYPE_LABELS = {
    "press_citation": "Press citations", "byline": "Bylines", "talk": "Talks",
    "tool_use": "Tool use", "dataset_use": "Dataset use", "policy_use": "Policy uptake",
    "grant_award": "Grants and awards", "endorsement": "Endorsements", "other": "Other",
}
HIGHLIGHTS = 8
IMPACT_ABOUT = ("Outcomes of Tal's work that are already public on a published page or quotable. "
                "Generated by scripts/sync_impact.py from the private ledger "
                "(nycur-data-premium/planning/impact_ledger.yaml, the source); "
                "edit the ledger, never this key.")


def valid_date(s: str, allow_month: bool) -> bool:
    try:
        if re.fullmatch(r"\d{4}-\d{2}-\d{2}", s):
            datetime.strptime(s, "%Y-%m-%d")
            return True
        if allow_month and re.fullmatch(r"\d{4}-\d{2}", s):
            datetime.strptime(s, "%Y-%m")
            return True
    except ValueError:
        pass
    return False


def load_ledger(path: Path) -> list[dict]:
    """Load and validate; exit loudly listing every problem."""
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    errors: list[str] = []
    if not isinstance(data, dict) or not isinstance(data.get("entries"), list):
        sys.exit(f"LEDGER INVALID: {path} needs a top-level 'entries' list")
    seen: set[str] = set()
    # Mentions Tal never wants in public copy (feedback_press_mentions_exclusions, Sep 15 2026); kept in the
    # ledger as `excluded_from_public` (URL substrings) so no sync can publish them (Oct 18 2026 audit)
    excluded = [x for x in (data.get("excluded_from_public") or []) if isinstance(x, str) and x]
    for i, e in enumerate(data["entries"]):
        where = f"entry #{i + 1}"
        if not isinstance(e, dict):
            errors.append(f"{where}: not a mapping")
            continue
        where = f"entry #{i + 1} ({e.get('id')!r})"
        for k in e:
            if k not in FIELDS:
                errors.append(f"{where}: unknown field {k!r}")
        for k in REQUIRED:
            if e.get(k) in (None, ""):
                errors.append(f"{where}: missing required field {k!r}")
        eid = e.get("id")
        if isinstance(eid, str) and eid:
            if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", eid):
                errors.append(f"{where}: id is not kebab-case")
            if eid in seen:
                errors.append(f"{where}: duplicate id")
            seen.add(eid)
        if e.get("type") is not None and e.get("type") not in TYPES:
            errors.append(f"{where}: type {e.get('type')!r} not in {TYPES}")
        if e.get("project") is not None and e.get("project") not in PROJECTS:
            errors.append(f"{where}: project {e.get('project')!r} not in {PROJECTS}")
        d = e.get("date")
        if d not in (None, "") and not (isinstance(d, str) and valid_date(d, True)):
            errors.append(f"{where}: date {d!r} must be a YYYY-MM-DD or YYYY-MM string")
        a = e.get("added")
        if a not in (None, "") and not (isinstance(a, str) and valid_date(a, False)):
            errors.append(f"{where}: added {a!r} must be a YYYY-MM-DD string")
        if "public" in e and not isinstance(e["public"], bool):
            errors.append(f"{where}: public must be true or false")
        u = e.get("url")
        if u is not None and not (isinstance(u, str) and re.match(r"https?://", u)):
            errors.append(f"{where}: url must be an http(s) URL or null")
        for k in ("title", "outlet", "summary", "source"):
            if e.get(k) not in (None, "") and not isinstance(e[k], str):
                errors.append(f"{where}: {k} must be a string")
        if e.get("public") is True and any(x in str(e.get("url") or "") or x in str(e.get("title") or "") for x in excluded):
            errors.append(f"{where}: on the excluded_from_public list; set public: false")
        # Oct 18 2026 audit: an unconfirmed fact cannot be public (it reached the profile highlights)
        if e.get("public") is True and re.search(r"(?i)to be confirmed|\bTBC\b|\bTBD\b|unconfirmed",
                                                   " ".join(str(e.get(k) or "") for k in ("summary", "title", "date"))):
            errors.append(f"{where}: public entry says it is unconfirmed; set public: false until Tal confirms")
    if errors:
        print(f"LEDGER INVALID: {len(errors)} problem(s) in {path}", file=sys.stderr)
        for m in errors:
            print(f"  - {m}", file=sys.stderr)
        sys.exit(1)
    return data["entries"]


def sort_key(e: dict) -> tuple:
    d = e["date"] if len(e["date"]) == 10 else e["date"] + "-00"
    return (d, e["id"])


def build_impact(entries: list[dict]) -> dict:
    pub = sorted((e for e in entries if e["public"]), key=sort_key, reverse=True)
    counts = {t: sum(1 for e in pub if e["type"] == t) for t in TYPES}
    return {
        "_about": IMPACT_ABOUT,
        "updated": date.today().isoformat(),
        "counts": {t: n for t, n in counts.items() if n},
        "highlights": [{k: e.get(k) for k in ("date", "type", "title", "outlet", "url")}
                       for e in pub[:HIGHLIGHTS]],
    }


def norm(s: str) -> str:
    return re.sub(r"\s+", " ", s.lower().replace("’", "'")).strip()


def reconcile(entries: list[dict], facts: dict) -> list[str]:
    """Report disagreements between public ledger entries and press/bylines/talks. Writes nothing."""
    pub = [e for e in entries if e["public"]]
    out: list[str] = []

    def side(kind: str, fact_names: list[str], ledger_type: str):
        led = {norm(e["outlet"]): e["outlet"] for e in pub if e["type"] == ledger_type}
        fact = {norm(n): n for n in fact_names}
        for k, v in sorted(led.items()):
            if k not in fact:
                out.append(f"{kind}: ledger outlet missing from profile_facts '{kind}': {v}")
        for k, v in sorted(fact.items()):
            if k not in led:
                out.append(f"{kind}: profile_facts '{kind}' item has no public {ledger_type} entry in the ledger: {v}")

    side("press", facts.get("press", []), "press_citation")
    side("bylines", facts.get("bylines", []), "byline")

    fact_talks = {(norm(t["title"]), t["date"][:7]): t for t in facts.get("talks", [])}
    led_talks = {(norm(e["title"]), e["date"][:7]): e for e in pub if e["type"] == "talk"}
    for k, e in sorted(led_talks.items()):
        if k not in fact_talks:
            out.append(f"talks: ledger talk missing from profile_facts 'talks': {e['date']} {e['title']} ({e['outlet']})")
    for k, t in sorted(fact_talks.items()):
        if k not in led_talks:
            out.append(f"talks: profile_facts 'talks' item has no public talk entry in the ledger: {t['date']} {t['title']}")
    return out


def impact_diff(old: dict | None, new: dict) -> str:
    a = json.dumps(old, indent=2, ensure_ascii=False).splitlines() if old is not None else []
    b = json.dumps(new, indent=2, ensure_ascii=False).splitlines()
    return "\n".join(difflib.unified_diff(a, b, "impact (current)", "impact (new)", lineterm="", n=1))


def export_markdown(entries: list[dict]) -> str:
    n_pub = sum(1 for e in entries if e["public"])
    lines = [
        "# Impact ledger export",
        "",
        f"Generated {date.today().isoformat()} by personal_website/scripts/sync_impact.py from "
        "nycur-data-premium/planning/impact_ledger.yaml. PRIVATE: for grant reports and applications; "
        "entries marked [PRIVATE] are not public and must not be quoted without checking the source.",
        "",
        f"{len(entries)} entries: {n_pub} public, {len(entries) - n_pub} private.",
        "",
    ]
    for t in TYPES:
        group = sorted((e for e in entries if e["type"] == t), key=sort_key, reverse=True)
        if not group:
            continue
        lines += [f"## {TYPE_LABELS[t]} ({len(group)})", ""]
        for e in group:
            tag = "" if e["public"] else " [PRIVATE]"
            lines.append(f"- **{e['date']}**{tag} {e['outlet']}: {e['title']}")
            lines.append(f"  - URL: {e['url'] or 'none'}")
            lines.append(f"  - {e['summary']}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ledger", required=True, type=Path)
    ap.add_argument("--check", action="store_true", help="print the report and the impact diff, write nothing")
    ap.add_argument("--export", type=Path, help="write the Markdown export of ALL entries to this path")
    args = ap.parse_args()

    entries = load_ledger(args.ledger)
    facts = json.loads(FACTS.read_text(encoding="utf-8"))
    impact = build_impact(entries)

    n_pub = sum(1 for e in entries if e["public"])
    print(f"Ledger OK: {len(entries)} entries, {n_pub} public, {len(entries) - n_pub} private.")
    print("\n## Reconcile report (nothing is changed in press, talks or bylines)")
    report = reconcile(entries, facts)
    print("\n".join(f"- {r}" for r in report) if report else "- press, bylines and talks agree with the public ledger")

    print("\n## impact diff")
    diff = impact_diff(facts.get("impact"), impact)
    print(diff or "(no change)")

    if args.export:
        args.export.parent.mkdir(parents=True, exist_ok=True)
        args.export.write_text(export_markdown(entries) + "\n", encoding="utf-8")
        print(f"\nExport written: {args.export}")

    if args.check:
        print("\n--check: nothing written to profile_facts.json")
        return 0
    facts["impact"] = impact
    FACTS.write_text(json.dumps(facts, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"\nWrote 'impact' to {FACTS}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
